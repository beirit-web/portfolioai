const fs = require("fs");
const path = require("path");

const repoRoot = path.resolve(__dirname, "..");
const sourcePath = path.join(repoRoot, "assets", "css", "main.css");
const outputPath = path.join(repoRoot, "assets", "css", "home-shell.css");

const ranges = [
  [1, 11],
  [286, 373],
  [521, 2483],
  [4649, 4683],
  [6048, 6143],
  [11091, 11418],
  [13163, 13208],
  [19929, 20178],
];

const lines = fs.readFileSync(sourcePath, "utf8").split(/\r?\n/);

function updateCssScanState(state, line) {
  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    const next = line[index + 1];

    if (state.inComment) {
      if (char === "*" && next === "/") {
        state.inComment = false;
        index += 1;
      }
      continue;
    }

    if (state.quote) {
      if (char === "\\" && next) {
        index += 1;
      } else if (char === state.quote) {
        state.quote = "";
      }
      continue;
    }

    if (char === "/" && next === "*") {
      state.inComment = true;
      index += 1;
      continue;
    }

    if (char === "\"" || char === "'") {
      state.quote = char;
      continue;
    }

    if (char === "{") state.depth += 1;
    if (char === "}") state.depth -= 1;
  }
}

function cssBalance(content) {
  const state = { depth: 0, quote: "", inComment: false };
  content.split(/\r?\n/).forEach((line) => updateCssScanState(state, line));
  return state.depth;
}

function topLevelBlocks(sourceLines) {
  const blocks = [];
  const state = { depth: 0, quote: "", inComment: false };
  let startLine = null;

  sourceLines.forEach((line, index) => {
    const trimmed = line.trim();
    if (startLine === null && trimmed) startLine = index + 1;

    updateCssScanState(state, line);

    if (state.depth < 0) {
      throw new Error(`CSS brace depth became negative near main.css:${index + 1}`);
    }

    if (startLine !== null && state.depth === 0 && trimmed) {
      blocks.push([startLine, index + 1]);
      startLine = null;
    }
  });

  if (state.depth !== 0) {
    throw new Error(`Source CSS is not balanced. Final brace depth: ${state.depth}`);
  }

  return blocks;
}

function intersects([blockStart, blockEnd], [rangeStart, rangeEnd]) {
  return blockStart <= rangeEnd && blockEnd >= rangeStart;
}

const blocks = topLevelBlocks(lines);
const selectedRanges = [];

ranges.forEach((range) => {
  blocks
    .filter((block) => intersects(block, range))
    .forEach((block) => {
      const previous = selectedRanges[selectedRanges.length - 1];
      if (previous && block[0] <= previous[1] + 1) {
        previous[1] = Math.max(previous[1], block[1]);
      } else {
        selectedRanges.push([...block]);
      }
    });
});

const chunks = selectedRanges.map(([start, end]) => {
  const content = lines.slice(start - 1, end).join("\n").trim();
  const balance = cssBalance(content);
  if (balance !== 0) {
    throw new Error(`Generated chunk main.css:${start}-${end} is not balanced: ${balance}`);
  }
  return `/* main.css:${start}-${end} */\n${content}`;
});

fs.writeFileSync(
  outputPath,
  [
    "/* Generated by scripts/build-home-shell-css.js. Do not edit manually. */",
    ...chunks,
    "",
  ].join("\n\n"),
);
